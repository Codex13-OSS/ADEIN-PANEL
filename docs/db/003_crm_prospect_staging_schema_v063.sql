CREATE TABLE IF NOT EXISTS crm_history_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  external_ref VARCHAR(120) NULL,
  source_ref VARCHAR(120) NULL,
  prospect_id BIGINT UNSIGNED NULL,
  followup_id BIGINT UNSIGNED NULL,
  conversation_id BIGINT UNSIGNED NULL,
  analysis_id BIGINT UNSIGNED NULL,
  seller_id BIGINT UNSIGNED NULL,
  actor_user_id BIGINT UNSIGNED NULL,
  source ENUM('whatsapp_txt','manual','demo','import') NOT NULL DEFAULT 'demo',
  environment ENUM('staging','production') NOT NULL DEFAULT 'staging',
  is_test BOOLEAN NOT NULL DEFAULT TRUE,
  is_demo BOOLEAN NOT NULL DEFAULT TRUE,
  review_status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
  event_type VARCHAR(80) NOT NULL,
  status VARCHAR(60) NULL,
  intention_level VARCHAR(60) NULL,
