-- v063: CRM Prospect Staging DB Schema Proposal (documentation-only, no execution by default)
-- Safe scope: prepares staging tables for prospect pipeline without using clients/contracts/payment_schedule.

CREATE TABLE IF NOT EXISTS lead_sources (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  source_code VARCHAR(40) NOT NULL,
  source_ref VARCHAR(120) NULL,
  environment ENUM('staging','production') NOT NULL DEFAULT 'staging',
  is_test BOOLEAN NOT NULL DEFAULT TRUE,
  is_demo BOOLEAN NOT NULL DEFAULT TRUE,
  review_status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
  raw_payload_json JSON NULL,
  normalized_payload_json JSON NULL,
  actor_user_id BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_lead_sources_actor_user FOREIGN KEY (actor_user_id) REFERENCES crm_users(id),
  UNIQUE KEY uq_lead_sources_code_ref_env (source_code, source_ref, environment)
);

CREATE TABLE IF NOT EXISTS prospects (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  external_ref VARCHAR(120) NULL,
  source_ref VARCHAR(120) NULL,
  source ENUM('whatsapp_txt','manual','demo','import') NOT NULL DEFAULT 'demo',
  environment ENUM('staging','production') NOT NULL DEFAULT 'staging',
  is_test BOOLEAN NOT NULL DEFAULT TRUE,
  is_demo BOOLEAN NOT NULL DEFAULT TRUE,
  review_status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
  lead_source_id BIGINT UNSIGNED NULL,
  seller_id BIGINT UNSIGNED NULL,
  actor_user_id BIGINT UNSIGNED NULL,
  name VARCHAR(160) NOT NULL,
  phone_original VARCHAR(60) NULL,
  phone_normalized VARCHAR(30) NULL,
  property_interest VARCHAR(160) NULL,
  status VARCHAR(60) NOT NULL DEFAULT 'new',
  intention_level VARCHAR(60) NULL,
  next_action VARCHAR(255) NULL,
  raw_payload_json JSON NULL,
  normalized_payload_json JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_prospects_lead_source FOREIGN KEY (lead_source_id) REFERENCES lead_sources(id),
  CONSTRAINT fk_prospects_seller FOREIGN KEY (seller_id) REFERENCES sellers(id),
  CONSTRAINT fk_prospects_actor_user FOREIGN KEY (actor_user_id) REFERENCES crm_users(id),
  KEY idx_prospects_phone_normalized (phone_normalized),
  KEY idx_prospects_status (status)
);

CREATE TABLE IF NOT EXISTS whatsapp_conversations (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
