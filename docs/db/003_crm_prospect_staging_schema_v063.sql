  actor_user_id BIGINT UNSIGNED NULL,
  source ENUM('whatsapp_txt','manual','demo','import') NOT NULL DEFAULT 'whatsapp_txt',
  environment ENUM('staging','production') NOT NULL DEFAULT 'staging',
  is_test BOOLEAN NOT NULL DEFAULT TRUE,
  is_demo BOOLEAN NOT NULL DEFAULT TRUE,
  review_status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
  phone_original VARCHAR(60) NULL,
  phone_normalized VARCHAR(30) NULL,
  raw_payload_json JSON NULL,
  normalized_payload_json JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_whatsapp_conversations_prospect FOREIGN KEY (prospect_id) REFERENCES prospects(id),
